// Builds docs/index.html (Guest) and docs/dev.html (Dev) as a static site (GitHub Pages) that calls the Apps Script
// web app's doPost JSON API with fetch(). Unlike pages served by script.google.com, it also works for
// visitors signed in to several Google accounts. Edit apps-script/Index.html, not docs/.
const fs = require('fs');
const path = require('path');

// The deployed web app (same deployment ID across redeploys).
const API_URL = 'https://script.google.com/macros/s/AKfycbzGmr4clWBx3d_TnrHlSGZU4-RlsuONVbDmKB4PEV-EC-m0Mulkg6rY73BjW8BSE_9C/exec';

const src = path.join(__dirname, '..', 'apps-script');
const read = n => fs.readFileSync(path.join(src, n + '.html'), 'utf8');

// Replaces google.script.run. Sent without cookies and as text/plain, so no Google login and no CORS preflight.
const apiShim = `<script>
  var API_URL = ${JSON.stringify(API_URL)};
  function rawCall(fn, args) {
    var ctl = typeof AbortController !== 'undefined' ? new AbortController() : null;
    var timer = ctl && setTimeout(function () { ctl.abort(); }, 90000);
    function transient(msg) { var e = new Error(msg); e.transient = true; return e; }
    return fetch(API_URL, { method: 'POST', credentials: 'omit', redirect: 'follow', signal: ctl ? ctl.signal : undefined,
      headers: { 'Content-Type': 'text/plain;charset=utf-8' }, body: JSON.stringify({ fn: fn, args: args }) })
      .then(function (r) {
        if (!r.ok) throw transient('Server tidak merespons (' + r.status + ').');
        return r.json().catch(function () { throw transient('Jawaban server tidak lengkap.'); });
      }, function () { throw transient('Tidak ada koneksi ke server.'); })
      .then(function (res) {
        clearTimeout(timer);
        if (res.ok) return res.result;
        var err = new Error(res.error);
        err.transient = /timed? ?out|too many|try again|Service (error|invoked)|Internal error|Server error|Lock timeout|unavailable/i.test(res.error);
        throw err;
      }, function (e) { clearTimeout(timer); throw e; });
  }
</script>`;

const params = `var QS = new URLSearchParams(location.search);
    function qp(k, re) { return String(QS.get(k) || '').replace(re, ''); }`;

function build(page, file, title, initVars) {
  let html = read(page);
  html = html.replace("<?!= include('Styles'); ?>", () => read('Styles'));
  html = html.replace("<?!= include('Shared'); ?>", () => read('Shared') + '\n' + apiShim);
  html = html.replace('<base target="_top">', '<meta name="viewport" content="width=device-width, initial-scale=1">\n  <title>' + title + '</title>');
  html = initVars(html);
  if (/<\?/.test(html)) throw new Error('Unreplaced template tag in ' + page);
  fs.writeFileSync(path.join(out, file), '<!-- Generated by scripts/build-guest.js from apps-script/. Do not edit. -->\n' + html);
  console.log('docs/' + file + ': ' + html.length + ' chars');
}

const out = path.join(__dirname, '..', 'docs');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, '.nojekyll'), '');

build('Index', 'index.html', 'BTC - Boarding Technician Camp', html => html.replace(
  /var INITIAL_BATCH = '<\?= initialBatch \?>', INITIAL_STAGE = '<\?= initialStage \?>', INITIAL_VIEW = '<\?= initialView \?>';/,
  () => params + `
    var INITIAL_BATCH = qp('batch', /[^A-Za-z0-9_-]/g), INITIAL_STAGE = qp('stage', /[^a-z0-9]/g),
      INITIAL_VIEW = QS.get('view') === 'dashboard' ? 'dashboard' : 'form';`));

// Dev: same password and token checks as on script.google.com; every Dev API call carries the token.
build('Dev', 'dev.html', 'BTC - Dev', html => html.replace(
  /var INITIAL_BATCH = '<\?= initialBatch \?>';/,
  () => params + `
    var INITIAL_BATCH = qp('batch', /[^A-Za-z0-9_-]/g);`));
console.log('API ' + API_URL);
