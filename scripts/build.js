// Bundles apps-script/ into one file, dist/Code.gs, so the whole app can be pasted
// into a single Code.gs in the Apps Script editor. HTML pages are embedded as strings.
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'apps-script');
const out = path.join(__dirname, '..', 'dist');
const scripts = ['Logic.gs', 'Code.gs', 'Setup.gs'];
const pages = fs.readdirSync(src).filter(f => f.endsWith('.html')).sort();

let code = '// Stage 1 - Akademi BTC: single-file build. Generated by scripts/build.js; edit apps-script/ instead.\n\n';
for (const f of scripts) code += `// ===== ${f} =====\n` + fs.readFileSync(path.join(src, f), 'utf8') + '\n';
code += '// ===== HTML pages =====\nvar HTML_FILES = {\n' + pages.map(f =>
  `  ${JSON.stringify(f.replace(/\.html$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(src, f), 'utf8'))}`).join(',\n') + '\n};\n';

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'Code.gs'), code);
console.log(`dist/Code.gs: ${code.length} chars, pages: ${pages.join(', ')}`);
